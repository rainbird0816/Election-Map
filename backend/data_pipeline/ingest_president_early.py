def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    for daesu, (year, cands, regions) in DATA.items():
        n = len(cands)
        totals = [0] * n
        for code, votes in regions.items():
            assert len(votes) == n, f"{daesu}대 {code} 후보수 불일치"
            for i, v in enumerate(votes):
                totals[i] += v
        assert totals == EXPECT[daesu], f"{daesu}대 전국합 불일치: {totals} != {EXPECT[daesu]}"

        cur.execute("DELETE FROM pres_cand WHERE daesu=?", (daesu,))
        cur.execute("DELETE FROM pres_region WHERE daesu=?", (daesu,))
        cur.execute("DELETE FROM pres_precinct WHERE daesu=?", (daesu,))
        for i, (party, name) in enumerate(cands):
            cur.execute("INSERT INTO pres_cand VALUES(?,?,?,?)", (daesu, i, party, name))
        for code, votes in regions.items():
            valid = sum(votes) or 1
            for i, v in enumerate(votes):
                cur.execute("INSERT INTO pres_region VALUES(?,?,?,?,?,?)",
                            (daesu, "시도", code, i, v, round(v / valid * 100, 2)))
        con.commit()
        print(f"{daesu}대({year}): 후보 {n} | 시도 {len(regions)} | 전국검증 OK")
        print(f"   {[f'{p}/{nm}' for p, nm in cands]}")
    con.close()


if __name__ == "__main__":
    main()
